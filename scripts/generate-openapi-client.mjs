#!/usr/bin/env node

/**
 * Generate a TypeScript client from /api/openapi.json.
 *
 * Usage:
 *   npm run generate:openapi
 *   npm run generate:openapi -- --spec <path>
 *   node scripts/generate-openapi-client.mjs [--spec <path>]
 *
 * Defaults to fetching from http://localhost:3000/api/openapi.json.
 * Pass --spec <path> to read from a local JSON file instead.
 *
 * Outputs: src/types/api-client.ts
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Node scripts are not RSC; stub the `server-only` marker so the shared
// OpenAPI generator can load outside Next.js.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier === "server-only") {
      return {
        shortCircuit: true,
        url: "data:text/javascript,export default {};",
      };
    }
    return nextResolve(specifier, context);
  },
});

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUTPUT = resolve(ROOT, "src/types/api-client.ts");

// ---------------------------------------------------------------------------
// Parse args
// ---------------------------------------------------------------------------
const args = process.argv.slice(2);
let specPath = null;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--spec" && args[i + 1]) {
    specPath = args[i + 1];
    break;
  }
}

// ---------------------------------------------------------------------------
// Load spec
// ---------------------------------------------------------------------------
async function loadSpec() {
  if (specPath) {
    const raw = readFileSync(resolve(ROOT, specPath), "utf-8");
    return JSON.parse(raw);
  }

  // Try to read from the dist/static output first, then fall back to fetch
  const staticPath = resolve(ROOT, ".next/static/api-openapi.json");
  try {
    const raw = readFileSync(staticPath, "utf-8");
    return JSON.parse(raw);
  } catch {
    // Fall back to running the spec generator directly
  }

  // Dynamic import to avoid bundling server-only modules in client builds
  const { generateOpenAPISpec } = await import("../src/lib/openapi-spec.ts");
  return generateOpenAPISpec("http://localhost:3000");
}

// ---------------------------------------------------------------------------
// Type generation (simplified openapi-typescript-style)
// ---------------------------------------------------------------------------

function schemaToType(schema, schemas) {
  if (!schema) return "unknown";

  if (schema.$ref) {
    const refName = schema.$ref.split("/").pop();
    return refName;
  }

  if (schema.type === "string") {
    if (schema.enum) return schema.enum.map((v) => `"${v}"`).join(" | ");
    return "string";
  }
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "array") {
    const inner = schemaToType(schema.items, schemas);
    return `${inner}[]`;
  }
  if (schema.type === "object") {
    if (!schema.properties) return "Record<string, unknown>";
    const lines = Object.entries(schema.properties).map(([key, prop]) => {
      const optional = !schema.required?.includes(key);
      const type = schemaToType(prop, schemas);
      return `  ${key}${optional ? "?" : ""}: ${type};`;
    });
    return `{\n${lines.join("\n")}\n}`;
  }

  return "unknown";
}

function generateTypes(spec) {
  const lines = [
    "// Auto-generated by scripts/generate-openapi-client.mjs",
    "// Do not edit manually — run `npm run generate:openapi` to regenerate.",
    "",
  ];

  // Generate component schemas as TypeScript types
  if (spec.components?.schemas) {
    for (const [name, schema] of Object.entries(spec.components.schemas)) {
      lines.push(`export type ${name} = ${schemaToType(schema, spec.components.schemas)};`);
      lines.push("");
    }
  }

  // Generate path parameter types
  lines.push("// ── Path parameters ──");
  lines.push("");

  // Generate response types for each path
  lines.push("// ── Response types ──");
  lines.push("");

  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(methods)) {
      if (typeof operation !== "object" || !operation.operationId) continue;
      const opId = operation.operationId;
      const response200 = operation.responses?.["200"];
      let responseType = "unknown";
      if (response200?.content?.["application/json"]?.schema) {
        responseType = schemaToType(
          response200.content["application/json"].schema,
          spec.components?.schemas
        );
      }

      lines.push(`/** ${operation.summary || `${method.toUpperCase()} ${path}`} */`);
      lines.push(
        `export type ${opId}_Response = ${responseType};`
      );
      lines.push("");
    }
  }

  // Generate fetcher wrapper
  lines.push("// ── Client helpers ──");
  lines.push("");
  lines.push("const BASE_URL = process.env.NEXT_PUBLIC_API_URL ?? '';");
  lines.push("");
  lines.push("type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH';");
  lines.push("");
  lines.push("interface RequestOptions {");
  lines.push("  params?: Record<string, string | number | undefined>;");
  lines.push("  body?: unknown;");
  lines.push("  headers?: Record<string, string>;");
  lines.push("  signal?: AbortSignal;");
  lines.push("}");
  lines.push("");
  lines.push("async function request<T>(method: HttpMethod, path: string, options: RequestOptions = {}): Promise<T> {");
  lines.push("  const url = new URL(path, BASE_URL || undefined);");
  lines.push("  if (options.params) {");
  lines.push("    for (const [k, v] of Object.entries(options.params)) {");
  lines.push("      if (v !== undefined) url.searchParams.set(k, String(v));");
  lines.push("    }");
  lines.push("  }");
  lines.push("  const res = await fetch(url.toString(), {");
  lines.push("    method,");
  lines.push("    headers: { 'Content-Type': 'application/json', ...options.headers },");
  lines.push("    body: options.body ? JSON.stringify(options.body) : undefined,");
  lines.push("    signal: options.signal,");
  lines.push("  });");
  lines.push("  if (!res.ok) {");
  lines.push("    const text = await res.text().catch(() => '');");
  lines.push("    throw new Error(`${method} ${path} failed: ${res.status} ${text}`);");
  lines.push("  }");
  lines.push("  return res.json() as Promise<T>;");
  lines.push("}");
  lines.push("");

  // Generate typed API functions
  lines.push("// ── Typed API functions ──");
  lines.push("");

  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(methods)) {
      if (typeof operation !== "object" || !operation.operationId) continue;
      const opId = operation.operationId;

      // Build function params from query/body params
      const params = (operation.parameters || [])
        .filter((p) => p.in === "query")
        .map((p) => {
          const type = schemaToType(p.schema, spec.components?.schemas);
          return `${p.name}${p.required ? "" : "?"}: ${type}`;
        });

      if (method === "post" && operation.requestBody) {
        const bodySchema =
          operation.requestBody?.content?.["application/json"]?.schema;
        if (bodySchema) {
          const bodyType = schemaToType(bodySchema, spec.components?.schemas);
          params.push(`body: ${bodyType}`);
        }
      }

      lines.push(
        `export async function ${opId}(${params.join(", ")}): Promise<${opId}_Response> {`
      );

      // Build function body
      const paramObj = (operation.parameters || [])
        .filter((p) => p.in === "query")
        .map((p) => p.name);
      if (paramObj.length > 0) {
        lines.push(
          `  return request<'${method.toUpperCase()}'>('${method.toUpperCase()}', '${path}', {`
        );
        lines.push(
          `    params: { ${paramObj.map((p) => `${p}: ${p}`).join(", ")} },`
        );
        if (method === "post") lines.push(`    body,`);
        lines.push(`  });`);
      } else if (method === "post") {
        lines.push(
          `  return request<'POST'>('POST', '${path}', { body });`
        );
      } else {
        lines.push(
          `  return request<'GET'>('GET', '${path}');`
        );
      }

      lines.push("}");
      lines.push("");
    }
  }

  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
async function main() {
  console.log("Loading OpenAPI spec...");
  const spec = await loadSpec();
  console.log(`  Found ${Object.keys(spec.paths || {}).length} paths`);

  console.log("Generating TypeScript client...");
  const code = generateTypes(spec);

  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, code, "utf-8");
  console.log(`  Written to ${OUTPUT}`);

  console.log("Done.");
}

main().catch((err) => {
  console.error("Failed to generate API client:", err);
  process.exit(1);
});
